// Renders the plugin tables in README.md from plugins/*/package.json and community.json.
// --check fails when README.md is out of date or an entry is invalid; --json prints the combined list.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = (path) => JSON.parse(readFileSync(new URL(path, root), "utf8"));
const KINDS = new Set(["runtime", "tooling"]);
const NPM = /^(@[a-z0-9-~][a-z0-9-._~]*\/)?debuff-plugin-[a-z0-9-]+$/;

const official = readdirSync(new URL("plugins/", root)).map((dir) => {
  const pkg = read(`plugins/${dir}/package.json`);
  return { name: pkg.name, description: pkg.description, repo: `plugins/${dir}`, kinds: ["runtime"] };
});

const errors = [];
const community = read("community.json").plugins.map((p, i) => {
  const where = `community.json plugins[${i}]`;
  if (typeof p.name !== "string" || !NPM.test(p.name))
    errors.push(`${where}: name must be an npm name like debuff-plugin-foo or @you/debuff-plugin-foo`);
  if (typeof p.description !== "string" || p.description.length > 120)
    errors.push(`${where}: description is required, 120 characters at most`);
  if (typeof p.repo !== "string" || !p.repo.startsWith("https://")) errors.push(`${where}: repo must be an https URL`);
  if (typeof p.author !== "string") errors.push(`${where}: author is required`);
  if (!Array.isArray(p.kinds) || p.kinds.length === 0 || !p.kinds.every((k) => KINDS.has(k)))
    errors.push(`${where}: kinds is a list of "runtime" and/or "tooling"`);
  return p;
});
const names = [...official, ...community].map((p) => p.name);
for (const n of names.filter((n, i) => names.indexOf(n) !== i)) errors.push(`${n} is listed twice`);
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

if (process.argv.includes("--json")) {
  console.log(JSON.stringify({ official, community }, null, 2));
  process.exit(0);
}

const npmLink = (name) => `[\`${name}\`](https://www.npmjs.com/package/${name})`;
const table = (rows, cols) =>
  rows.length === 0
    ? "_None yet. Yours could be first: see [Add your plugin](#add-your-plugin)._"
    : [
        `| ${cols.map((c) => c[0]).join(" | ")} |`,
        `| ${cols.map(() => "---").join(" | ")} |`,
        ...rows.map((r) => `| ${cols.map((c) => c[1](r)).join(" | ")} |`),
      ].join("\n");

const generated = [
  "<!-- registry:start (generated by npm run registry, do not edit) -->",
  "",
  "### Official",
  "",
  table(official, [
    ["Package", (p) => npmLink(p.name)],
    ["What it does", (p) => p.description],
    ["Source", (p) => `[${p.repo}](${p.repo})`],
  ]),
  "",
  "### Community",
  "",
  table(community, [
    ["Package", (p) => npmLink(p.name)],
    ["What it does", (p) => p.description],
    ["Kind", (p) => p.kinds.join(", ")],
    ["By", (p) => `[${p.author}](${p.repo})`],
  ]),
  "",
  "<!-- registry:end -->",
].join("\n");

const readmeUrl = new URL("README.md", root);
const readme = readFileSync(readmeUrl, "utf8");
const next = readme.replace(/<!-- registry:start[\s\S]*?<!-- registry:end -->/, generated);
if (process.argv.includes("--check")) {
  if (next !== readme) {
    console.error("README.md plugin tables are out of date: run npm run registry");
    process.exit(1);
  }
} else writeFileSync(readmeUrl, next);
